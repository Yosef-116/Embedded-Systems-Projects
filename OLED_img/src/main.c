// 6. Display Draw Function
void OLED_DrawBitmap(const uint8_t *bitmap) {
  uint16_t pointer = 0;
  
  // Loop through all 8 pages (vertical sections)
  for (uint8_t page = 0; page < 8; page++) { 
    OLED_WriteCmd(0xB0 + page); // Set active page 0-7
    OLED_WriteCmd(0x00);       // Set lower column address to 0
    OLED_WriteCmd(0x10);       // Set higher column address to 0
    
    // Send 128 columns of data for this page
    for (uint8_t col = 0; col < 128; col++) { 
      // Read a byte from Flash Memory (PROGMEM)
      uint8_t pixel_byte = pgm_read_byte(&(bitmap[pointer++])); 
      
      // Write the physical pixel column to the OLED
      OLED_WriteData(pixel_byte); 
    } 
  } 
}


int main(void) { 
  I2C_Init(); 
  OLED_Init(); 
  OLED_Clear(); 
  
  // Draw the custom image from Flash memory
  OLED_DrawBitmap(epd_bitmap_images); 
  
  while (1) { 
    // The image remains on the screen statically
  } 
}